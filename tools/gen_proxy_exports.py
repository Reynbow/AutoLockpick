"""Generates src/proxy_exports.h: linker directives that forward every export of the system
dsound.dll, so the mod can be dropped next to the game as dsound.dll.

Reads the export table of C:\\Windows\\System32\\dsound.dll directly (no Visual Studio tools needed).

Usage: python tools/gen_proxy_exports.py
"""
import os
import struct

DLL = 'dsound'
SYSTEM_DLL = os.path.join(os.environ.get('SystemRoot', r'C:\Windows'), 'System32', DLL + '.dll')
# Forward through the NT object namespace so the path doesn't depend on the drive Windows lives on.
TARGET = '\\\\.\\GLOBALROOT\\SystemRoot\\System32\\' + DLL
# COM entry points: looked up by name only, so they're exported without an ordinal and kept out of
# the import library (the linker warns otherwise). The game imports dsound's other exports by
# ordinal, so those keep the system DLL's ordinals.
PRIVATE = {'DllCanUnloadNow', 'DllGetClassObject', 'DllRegisterServer', 'DllUnregisterServer'}


def exports(path):
    """(ordinal, name or None) for every export of a 64-bit PE file, in ordinal order."""
    data = open(path, 'rb').read()
    pe = struct.unpack_from('<I', data, 0x3C)[0]
    sections = struct.unpack_from('<H', data, pe + 6)[0]
    optional_size = struct.unpack_from('<H', data, pe + 20)[0]
    optional = pe + 24
    if struct.unpack_from('<H', data, optional)[0] != 0x20B:
        raise SystemExit('%s is not a 64-bit DLL' % path)
    export_rva = struct.unpack_from('<I', data, optional + 112)[0]
    table = [struct.unpack_from('<IIII', data, optional + optional_size + 40 * i + 8) for i in range(sections)]

    def offset(rva):
        for virtual_size, virtual_address, raw_size, raw_pointer in table:
            if virtual_address <= rva < virtual_address + max(virtual_size, raw_size):
                return raw_pointer + rva - virtual_address
        raise ValueError('RVA 0x%x is in no section' % rva)

    def text(rva):
        o = offset(rva)
        return data[o:data.index(b'\0', o)].decode('ascii')

    (base, functions, names, function_rvas, name_rvas,
     name_ordinals) = struct.unpack_from('<IIIIII', data, offset(export_rva) + 16)
    named = {}
    for i in range(names):
        index = struct.unpack_from('<H', data, offset(name_ordinals) + 2 * i)[0]
        named[index] = text(struct.unpack_from('<I', data, offset(name_rvas) + 4 * i)[0])
    return [(base + i, named.get(i)) for i in range(functions)
            if struct.unpack_from('<I', data, offset(function_rvas) + 4 * i)[0]]


def main():
    rows = exports(SYSTEM_DLL)
    esc = TARGET.replace('\\', '\\\\')
    dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'proxy_exports.h')
    with open(dst, 'w', newline='\n') as f:
        f.write('// Generated by tools/gen_proxy_exports.py from %s. Do not edit.\n' % SYSTEM_DLL)
        f.write('// Every export forwards to the real system DLL.\n#pragma once\n\n')
        for ordinal, name in rows:
            if name is None:
                f.write('#pragma comment(linker, "/export:__proxy_ord%d=%s.#%d,@%d,NONAME")\n' % (ordinal, esc, ordinal, ordinal))
            elif name in PRIVATE:
                f.write('#pragma comment(linker, "/export:%s=%s.%s,PRIVATE")\n' % (name, esc, name))
            else:
                f.write('#pragma comment(linker, "/export:%s=%s.%s,@%d")\n' % (name, esc, name, ordinal))
    print('wrote %d exports to %s' % (len(rows), os.path.normpath(dst)))


if __name__ == '__main__':
    main()
